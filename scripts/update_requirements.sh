#!/usr/bin/env bash
# Regenerate requirements.txt and requirements-dev.txt (exact versions + sha256 hashes) from requirements.in
# and requirements-dev.in. The dev lock is constrained by the runtime lock, so tests run the versions production runs.
# Needs `uv` (https://docs.astral.sh/uv/) on the machine that regenerates; target nodes only need pip.
#   ./scripts/update_requirements.sh              keep current pins where still valid, add what is new
#   ./scripts/update_requirements.sh --upgrade    move every pin to the newest allowed version
# The lock is universal: one file for Python >= 3.9 (RHEL 9 default) on any CPU, with environment markers.
# After regenerating: run ./scripts/ci_check.sh, test, and commit requirements.in + requirements.txt together.
set -euo pipefail
cd "$(dirname "$0")/.."
command -v uv >/dev/null || { echo "ERROR: uv not found (pip install uv, or see https://docs.astral.sh/uv/)" >&2; exit 1; }
extra=()
[ "${1:-}" = "--upgrade" ] && extra=(--upgrade)
uv pip compile requirements.in --python-version 3.9 --universal --generate-hashes \
    --no-header --quiet ${extra[@]+"${extra[@]}"} -o requirements.txt.tmp
{
  echo "# GENERATED by scripts/update_requirements.sh from requirements.in. Do not edit by hand."
  echo "# Install with: pip install --require-hashes -r requirements.txt"
  cat requirements.txt.tmp
} > requirements.txt
rm -f requirements.txt.tmp
# Dev tools (pytest, ruff): CI/test hosts only. -c keeps every shared package at the runtime pin.
uv pip compile requirements-dev.in --python-version 3.9 --universal --generate-hashes \
    --no-header --quiet -o requirements-dev.txt.tmp
{
  echo "# GENERATED by scripts/update_requirements.sh from requirements-dev.in. Do not edit by hand."
  echo "# Install with: pip install --require-hashes -r requirements.txt -r requirements-dev.txt"
  cat requirements-dev.txt.tmp
} > requirements-dev.txt
rm -f requirements-dev.txt.tmp
echo "requirements.txt regenerated: $(grep -cE '^[A-Za-z0-9_.-]+==' requirements.txt) pinned lines"
