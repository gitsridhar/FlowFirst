#!/usr/bin/env bash
# ==============================================================================
# FlowFirst PKI - create the self-signed root CA (run ONCE, on the admin/CA host).
#
#   ./security/init_ca.sh            create pki/ca/{ca.key,ca.crt,ca.crl,...}
#
# The CA private key is encrypted (AES-256) with a passphrase you choose. Keep the
# key and the passphrase off the cluster nodes: nodes only ever receive ca.crt
# (public) and their own leaf key/certificate pairs.
# ==============================================================================
set -euo pipefail
# shellcheck disable=SC1091
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

require_openssl
require_int PKI_CA_BITS "${PKI_CA_BITS}"; require_int PKI_CA_DAYS "${PKI_CA_DAYS}"; require_int PKI_CRL_DAYS "${PKI_CRL_DAYS}"
validate_cn "${PKI_CA_CN}"
[[ "${PKI_ORG}" =~ ^[A-Za-z0-9][A-Za-z0-9._\ -]{0,63}$ ]] || die "Invalid PKI_ORG '${PKI_ORG}'."

if ca_present; then
    die "A CA already exists in ${CA_DIR}. Refusing to overwrite it (that would invalidate every issued certificate). Remove ${PKI_DIR} deliberately if you really want to start over."
fi

if [[ -z "${PKI_CA_PASS:-}" && -z "${PKI_CA_PASSPHRASE_FILE:-}" ]]; then
    [[ -t 0 ]] || die "Set PKI_CA_PASSPHRASE_FILE (a file, mode 600, first line = passphrase) when not run from a terminal."
    read -r -s -p "Choose a CA key passphrase (min 12 characters): " PKI_CA_PASS; echo >&2
    read -r -s -p "Repeat it: " _again; echo >&2
    [[ "${PKI_CA_PASS}" == "${_again}" ]] || die "Passphrases differ."
    export PKI_CA_PASS
else
    ca_pass_init
fi
[[ ${#PKI_CA_PASS} -ge 12 ]] || die "The CA passphrase must be at least 12 characters."

umask 077
mkdir -p "${CA_DIR}/newcerts" "${ISSUED_DIR}"
: > "${CA_DIR}/index.txt"
echo 1000 > "${CA_DIR}/serial"
echo 1000 > "${CA_DIR}/crlnumber"

cat > "${CA_DIR}/ca.cnf" <<EOF
# FlowFirst root CA configuration (generated by security/init_ca.sh)
[ ca ]
default_ca = CA_default

[ CA_default ]
dir              = ${CA_DIR}
database         = \$dir/index.txt
new_certs_dir    = \$dir/newcerts
serial           = \$dir/serial
crlnumber        = \$dir/crlnumber
certificate      = \$dir/ca.crt
private_key      = \$dir/ca.key
default_md       = sha256
default_days     = ${PKI_LEAF_DAYS}
default_crl_days = ${PKI_CRL_DAYS}
unique_subject   = no
policy           = policy_flowfirst
copy_extensions  = none
preserve         = no

[ policy_flowfirst ]
organizationName       = supplied
organizationalUnitName = optional
commonName             = supplied

[ req ]
distinguished_name = req_dn
prompt             = no
string_mask        = utf8only

[ req_dn ]
O  = ${PKI_ORG}
CN = ${PKI_CA_CN}

[ v3_ca ]
subjectKeyIdentifier   = hash
authorityKeyIdentifier = keyid:always
basicConstraints       = critical, CA:true, pathlen:0
keyUsage               = critical, keyCertSign, cRLSign
EOF

echo "Creating root CA '${PKI_CA_CN}' (RSA ${PKI_CA_BITS}, ${PKI_CA_DAYS} days) in ${CA_DIR} ..."
openssl genrsa -aes256 -passout env:PKI_CA_PASS -out "${CA_DIR}/ca.key" "${PKI_CA_BITS}" 2>/dev/null
ca_key_unlock
openssl req -x509 -new -sha256 -config "${CA_DIR}/ca.cnf" -extensions v3_ca \
    -key "${CA_KEY_PLAIN}" -days "${PKI_CA_DAYS}" -out "${CA_DIR}/ca.crt"
chmod 600 "${CA_DIR}/ca.key"; chmod 644 "${CA_DIR}/ca.crt"
gen_crl

echo
openssl x509 -in "${CA_DIR}/ca.crt" -noout -subject -issuer -dates -fingerprint -sha256
echo
echo "Done."
echo "  Public CA certificate (distribute to every node and client): ${CA_DIR}/ca.crt"
echo "  CA private key (keep OFFLINE / on this host only):           ${CA_DIR}/ca.key"
echo "  Next: ./security/issue_all.sh   (issues the certificates for every node and use-case)"
